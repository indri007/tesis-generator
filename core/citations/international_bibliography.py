def format_apa7(entry: dict[str, Any]) -> str:
    """Formats a bibliography entry into APA 7th edition string."""
    authors = ", ".join(entry["authors"])
    year = entry["year"]
    title = entry["title"]
    journal = entry["journal"]
    volume = entry.get("volume", "")
    issue = f"({entry['issue']})" if entry.get("issue") else ""
    pages = f", {entry['pages']}" if entry.get("pages") else ""
    doi = f"https://doi.org/{entry['doi']}"

    return f"{authors} ({year}). {title}. {journal}, {volume}{issue}{pages}. {doi}"


def get_all_apa7_references() -> list[str]:
    """Returns all 35 references formatted in standard APA 7th edition."""
    return [format_apa7(e) for e in INTERNATIONAL_BIBLIOGRAPHY_35]


def verify_bibliography_standards(
    min_count: int = 35,
    min_year: int = 2021,
    max_year: int = 2026,
) -> dict[str, Any]:
    """Audits the bibliography against official MIKOM 2026 international currency rules."""
    total = len(INTERNATIONAL_BIBLIOGRAPHY_35)
    valid_count = total >= min_count

    doi_valid_count = 0
    year_valid_count = 0
    invalid_entries = []

    doi_regex = r"^10\.\d{4,9}/[-._;()/:A-Za-z0-9]+$"

    for e in INTERNATIONAL_BIBLIOGRAPHY_35:
        is_doi_ok = bool(re.match(doi_regex, e.get("doi", "")))
        is_year_ok = min_year <= int(e.get("year", 0)) <= max_year

        if is_doi_ok:
            doi_valid_count += 1
        if is_year_ok:
            year_valid_count += 1

        if not (is_doi_ok and is_year_ok):
            invalid_entries.append({"id": e.get("id"), "doi_ok": is_doi_ok, "year_ok": is_year_ok})

    q1_count = sum(1 for e in INTERNATIONAL_BIBLIOGRAPHY_35 if e.get("quartile") == "Q1")
    q2_count = sum(1 for e in INTERNATIONAL_BIBLIOGRAPHY_35 if e.get("quartile") == "Q2")

    is_compliant = valid_count and (doi_valid_count == total) and (year_valid_count == total)

    return {
        "is_compliant": is_compliant,
        "total_references": total,
        "required_min_count": min_count,
        "valid_dois_count": doi_valid_count,
        "valid_years_count": year_valid_count,
        "year_window": f"{min_year}–{max_year}",
        "q1_count": q1_count,
        "q2_count": q2_count,
        "invalid_entries": invalid_entries,
    }
